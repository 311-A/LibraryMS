#include <iostream>
#include "Library.h"

/* ==========================================================================
 *  程序入口
 * --------------------------------------------------------------------------
 *  main 里只做一件事：创建一个图书馆对象，然后把控制权交给它的菜单循环。
 *  所有资源对象、学生对象的 new / delete 都在 Library / Repository 内部完成。
 *
 *  【实验六】Library 的构造函数会自动从 library_data.txt 读档；
 *           选择 0 退出时又会写回该文件，所以重启程序数据还在。
 * ========================================================================== */
int main()
{
    Library library("library_data.txt");   // 构造时自动读档（读不到就载入示例数据）
    library.run();                         // 进入菜单

    std::cout << "\n>>> 按回车键关闭窗口…";
    std::cin.get();
    return 0;
}
